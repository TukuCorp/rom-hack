import re, sys, zipfile

TABLES = [("datanames", "Freedonia/datanames.nx1"),
          ("masterstructure", "Freedonia/masterstructure.nx1"),
          ("scenariodata", "Freedonia/scenariodata.nx1")]
WINDOW = 0x9000
NUL2 = bytes(2)


def wide_strings(buf, end):
    """Distinct NUL-terminated UTF-16 runs of five or more printable characters."""
    end = min(end, len(buf))
    out = []
    at = 0
    while at + 12 <= end:
        if 32 <= buf[at] < 127 and buf[at + 1] == 0:
            n = 0
            while at + 2 * n + 1 < end and 32 <= buf[at + 2 * n] < 127 and buf[at + 2 * n + 1] == 0:
                n += 1
            if n >= 5 and buf[at + 2 * n:at + 2 * n + 2] == NUL2:
                text = buf[at:at + 2 * n].decode("utf-16-le").strip()
                if text and text not in out:
                    out.append(text)
                at += 2 * n
                continue
        at += 1
    return out


def esc(s):
    return s.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))


DOMAIN = {
    "datanames": ["Electricity", "Oil Products", "Natural Gas", "Nuclear", "Renewables"],
    "masterstructure": ["Load Shapes", "Land Areas", "Effects", "Indicators", "Freedonia"],
    "scenariodata": ["@F001(@F010(3))", "@F176*(1-@F185)*(@C0004/@C0003)"],
}


def main(out):
    rows = []
    with zipfile.ZipFile("C:/Program Files/LEAP/Freedonia.zip") as zf:
        for name, member in TABLES:
            raw = zf.read(member)
            window = raw[:WINDOW]
            rows.append((name, window, wide_strings(window, WINDOW)))
        ini = zf.read("Freedonia/areasettingsINI.txt").decode("latin-1")
    ini_keys = sorted(set(re.findall(r"(?m)^([A-Za-z_][A-Za-z0-9_]*)=", ini)))
    year = re.search(r"(?m)^EBalYearID=([0-9]+)", ini)

    lines = []
    lines.append("// GENERATED by tools/capture_nx1_strings.py -- do not edit by hand.")
    lines.append("//")
    lines.append("// The first 0x9000 bytes of three tables from the Freedonia area that ships with")
    lines.append("// LEAP, with the wide strings the reference reader finds in each. The records are")
    lines.append("// plain UTF-16, so the model names and expressions are readable with no cipher.")
    lines.append("//")
    lines.append("// (table, window bytes as hex, distinct wide strings in first-seen order)")
    lines.append("pub const NX1_STRINGS: &[(&str, &str, &[&str])] = &[")
    for name, window, strings in rows:
        lines.append("    // %s: %d strings in a %d byte window" % (name, len(strings), len(window)))
        cells = ", ".join(chr(34) + esc(s) + chr(34) for s in strings)
        lines.append("    (%s, %s, &[%s]),"
                     % (chr(34) + name + chr(34), chr(34) + window.hex() + chr(34), cells))
    lines.append("];")
    lines.append("")
    lines.append("/// Model names that must appear, taken from what LEAP itself calls these things")
    lines.append("/// rather than from a second reading of the file.")
    lines.append("pub const NX1_DOMAIN_NAMES: &[(&str, &str)] = &[")
    for table, names in DOMAIN.items():
        for n in names:
            lines.append("    (%s, %s)," % (chr(34) + table + chr(34), chr(34) + esc(n) + chr(34)))
    lines.append("];")
    lines.append("")
    lines.append("/// The area settings file states a base year, and the tables carry the year list.")
    lines.append("/// Nothing about that check depends on this reader.")
    lines.append("pub const NX1_INI_BASE_YEAR: u32 = %s;" % (year.group(1) if year else 0))
    with open(out, "w", encoding="utf-8", newline=chr(10)) as fh:
        fh.write(chr(10).join(lines) + chr(10))

    print("wrote %s" % out)
    for name, window, strings in rows:
        print("  %-16s %d strings" % (name, len(strings)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
