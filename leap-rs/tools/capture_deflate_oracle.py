#!/usr/bin/env python3
"""Capture a raw DEFLATE conformance corpus with zlib, for the crate inflater.

The container oracle only ever inflates the small sysinfo.txt bodies of the .leap
archives, which leaves whole parts of the decoder untested: back-reference copies at
long distances, dynamic Huffman tables, and stored blocks. This corpus compresses
plaintexts built to force each of those, and stores the stream next to the recipe for
its plaintext so the Rust test can rebuild the expected bytes exactly.

A vector is (case, compressed stream, prefix block, repeated block, repeat count, level)
and the plaintext is prefix + block * repeats. Writes src/oracle_deflate.rs.
"""

import argparse
import random
import sys
import zlib


def block_random(n, seed):
    rng = random.Random(seed)
    return bytes(rng.randrange(256) for _ in range(n))


def block_text(n, seed):
    rng = random.Random(seed)
    words = [b"sector", b"energy", b"demand", b"supply", b"year", b"region", b"scenario"]
    out = bytearray()
    while len(out) < n:
        out += b" " + rng.choice(words)
    return bytes(out[:n])


def raw_deflate(data, level):
    co = zlib.compressobj(level, zlib.DEFLATED, -15)
    return co.compress(data) + co.flush()


def vectors():
    out = []
    out.append(("empty", b"", b"", 0, 6))
    out.append(("single_byte", b"", b"A", 1, 6))
    out.append(("one_byte_repeated", b"", b"Z", 40000, 6))
    out.append(("short_pattern_repeated", b"", block_text(37, 1), 1000, 6))
    out.append(("wide_block_repeated", b"", block_random(4096, 7), 16, 6))
    out.append(("incompressible", b"", block_random(1024, 11), 1, 6))
    out.append(("incompressible_multi", b"", block_random(2048, 13), 3, 6))
    out.append(("stored_level0", b"", block_text(600, 17), 2, 0))
    out.append(("fast_level1", b"", block_text(900, 19), 3, 1))
    out.append(("best_level9", b"", block_text(1500, 23), 2, 9))
    # A long incompressible prefix, then a copy of its first bytes, so the only match
    # available sits a long way back. zlib will only reach back 32506 bytes, not the
    # 32768 the format allows, so 32000 keeps the distance usable instead of forcing a
    # stored block.
    far = block_random(32000, 41)
    out.append(("long_distance", far, far[:300], 1, 9))
    out.append(("mixed", block_random(64, 29), block_text(200, 31), 5, 6))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rows = []
    for name, prefix, block, repeats, level in vectors():
        plain = prefix + block * repeats
        rows.append((name, prefix, block, repeats, level, plain, raw_deflate(plain, level)))

    lines = []
    lines.append("// GENERATED by tools/capture_deflate_oracle.py -- do not edit by hand.")
    lines.append("// Raw DEFLATE streams from zlib, with the recipe for each plaintext so the")
    lines.append("// test can rebuild the expected bytes exactly: plaintext = prefix + block * n.")
    lines.append("//")
    lines.append("// (case, compressed stream as hex, prefix as hex, block as hex, n, zlib level)")
    lines.append("pub const DEFLATE_VECTORS: &[(&str, &str, &str, &str, usize, i32)] = &[")
    for name, prefix, block, repeats, level, plain, comp in rows:
        lines.append("    // %d plaintext bytes, %d compressed" % (len(plain), len(comp)))
        lines.append('    ("%s", "%s", "%s", "%s", %d, %d),'
            .replace(chr(10), "")
                     % (name, comp.hex(), prefix.hex(), block.hex(), repeats, level))
    lines.append("];")
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(chr(10).join(lines) + chr(10))

    print("wrote %s with %d vectors" % (args.out, len(rows)))
    for name, prefix, block, repeats, level, plain, comp in rows:
        ratio = (100.0 * len(comp) / len(plain)) if plain else 0.0
        print("  %-22s plain=%7d comp=%6d level=%d (%5.1f%%)"
              % (name, len(plain), len(comp), level, ratio))
    return 0


if __name__ == "__main__":
    sys.exit(main())
