import re, sys, zipfile

TABLES = [("areadata", "Freedonia/areadata.nx1"),
          ("years", "Freedonia/years.nx1"),
          ("masterstructure", "Freedonia/masterstructure.nx1")]
WINDOW = 0x8000


def tagged_strings(buf, end):
    out = []
    at = 0
    while at < end - 2:
        if buf[at] in (0x06, 0x07):
            n = buf[at + 1]
            if 1 <= n <= 64 and at + 2 + n <= end:
                chunk = buf[at + 2:at + 2 + n]
                if all(32 <= c < 127 for c in chunk):
                    out.append(chunk.decode("latin-1"))
                    at += 2 + n
                    continue
        at += 1
    return out


def extract(raw, end):
    strings = tagged_strings(raw, end)
    fields = []
    indexes = []
    for i, text in enumerate(strings):
        if text == "TnxFieldDescriptor" and i + 2 < len(strings):
            pair = (strings[i + 1], strings[i + 2])
            if pair not in fields:
                fields.append(pair)
        elif text == "TnxIndexDescriptor" and i + 1 < len(strings):
            name = strings[i + 1]
            if name not in indexes:
                indexes.append(name)
    return fields, indexes


def esc(s):
    return s.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))


def main(out):
    with zipfile.ZipFile("C:/Program Files/LEAP/Freedonia.zip") as zf:
        ini = zf.read("Freedonia/areasettingsINI.txt").decode("latin-1")
        keys = set(re.findall(r"(?m)^([A-Za-z_][A-Za-z0-9_]*)=", ini))
        rows = []
        for name, member in TABLES:
            raw = zf.read(member)
            window = min(WINDOW, len(raw))
            fields, indexes = extract(raw, window)
            rows.append((name, raw[:window], fields, indexes))

    overlap = sorted({f for _, _, fields, _ in rows for f, _ in fields} & keys)

    lines = []
    lines.append("// GENERATED by tools/capture_nx1_oracle.py -- do not edit by hand.")
    lines.append("//")
    lines.append("// The first 0x8000 bytes of three tables from the Freedonia area that ships")
    lines.append("// with LEAP, with the field and index names the reference parser reads out of")
    lines.append("// each. The bytes are stored so the Rust test needs nothing installed.")
    lines.append("//")
    lines.append("// (table, dictionary bytes as hex, fields as (name, type), index names)")
    lines.append("pub const NX1_TABLES: &[(&str, &str, &[(&str, &str)], &[&str])] = &[")
    for name, window, fields, indexes in rows:
        lines.append("    // %s: %d fields, %d indexes" % (name, len(fields), len(indexes)))
        pairs = ", ".join("(%s, %s)" % (chr(34) + esc(f) + chr(34), chr(34) + esc(t) + chr(34))
                          for f, t in fields)
        idx = ", ".join(chr(34) + esc(i) + chr(34) for i in indexes)
        lines.append("    (%s, %s, &[%s], &[%s]),"
                     % (chr(34) + name + chr(34), chr(34) + window.hex() + chr(34), pairs, idx))
    lines.append("];")
    lines.append("")
    lines.append("/// Field names that also appear as keys in the area plain-text settings file,")
    lines.append("/// which is an independent artefact rather than another reading of the table.")
    lines.append("pub const NX1_INI_OVERLAP: &[&str] = &[")
    for k in overlap:
        lines.append("    %s," % (chr(34) + esc(k) + chr(34)))
    lines.append("];")
    with open(out, "w", encoding="utf-8", newline=chr(10)) as fh:
        fh.write(chr(10).join(lines) + chr(10))

    print("wrote %s" % out)
    for name, window, fields, indexes in rows:
        print("  %-16s %d fields, %d indexes, window %d bytes" % (name, len(fields), len(indexes), len(window)))
    print("  field names that are also INI keys: %d" % len(overlap))
    for k in overlap[:15]:
        print("     " + k)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
