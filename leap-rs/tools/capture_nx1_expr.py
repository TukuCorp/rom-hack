"""Capture the expression corpus out of the LEAP area tables that ship with LEAP.

The scenario table stores the model arithmetic as plain UTF-16 text, so the expressions
are readable with no cipher. This script finds them and writes src/oracle_nx1_expr.rs.

The rule is deliberately narrow, and it is the same rule the Rust reader implements, so
the two can be compared rather than one being believed:

  * a NUL-terminated run of UTF-16 code units drawn from printable ASCII plus U+00A4,
    the last one being the character LEAP wraps a series literal in;
  * at least four characters long;
  * containing one of the markers @F, @V or @C.

The alphabet matters. A reader that only accepts ASCII silently drops every expression
that carries a series literal, which is how the first reading of this table came up
short. The marker test matters too: the tables also hold URL-encoded HTML whose @page
rule would otherwise be read as an expression.

Each entry carries the byte window the expression was read from, taken from the vendor
file, so the Rust side can re-run its own scanner against the original bytes rather than
against its own output.

Usage: python tools/capture_nx1_expr.py leap-rs/src/oracle_nx1_expr.rs
"""

import re
import sys
import zipfile

WIDE = re.compile(rb"(?:[\x20-\x7e\xa4]\x00){4,}")
MARKERS = ("@F", "@V", "@C")
LEAP_ZIP = "C:/Program Files/LEAP/Freedonia.zip"


def scan(raw):
    """Distinct NUL-terminated wide strings that look like an expression."""
    out = []
    for m in WIDE.finditer(raw):
        if raw[m.end():m.end() + 2] != bytes(2):
            continue
        text = m.group().decode("utf-16-le").strip()
        if not any(k in text for k in MARKERS):
            continue
        if text not in out:
            out.append(text)
    return out


def windows(raw):
    """Every expression in raw, with the byte window it was read from."""
    found = []
    seen = set()
    for m in WIDE.finditer(raw):
        if raw[m.end():m.end() + 2] != bytes(2):
            continue
        text = m.group().decode("utf-16-le").strip()
        if not any(k in text for k in MARKERS):
            continue
        if text in seen:
            continue
        seen.add(text)
        window = None
        for lead in (2, 1, 0):
            lo = max(0, m.start() - lead)
            hi = min(len(raw), m.end() + 4)
            if scan(raw[lo:hi]) == [text]:
                window = raw[lo:hi]
                break
        if window is None:
            raise SystemExit("no window re-scans to %r" % text)
        found.append((text, m.start(), window))
    return found


def put(s):
    """A Rust string literal; anything outside printable ASCII becomes an escape."""
    out = []
    for ch in s:
        if ch == chr(34):
            out.append(chr(92) + chr(34))
        elif ch == chr(92):
            out.append(chr(92) * 2)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append(chr(92) + "u{%x}" % ord(ch))
    return chr(34) + "".join(out) + chr(34)


def main(out):
    rows = []
    with zipfile.ZipFile(LEAP_ZIP) as zf:
        for member in sorted(zf.namelist()):
            if not member.lower().endswith(".nx1"):
                continue
            raw = zf.read(member)
            for text, at, window in windows(raw):
                rows.append((member.rsplit("/", 1)[-1], at, window, text))

    lines = []
    lines.append("// GENERATED by tools/capture_nx1_expr.py -- do not edit by hand.")
    lines.append("//")
    lines.append("// Every expression the LEAP area tables carry, with the byte window each one")
    lines.append("// was read from. The text is the vendor's own, so the round-trip test in")
    lines.append("// tests/nx1_expr.rs runs against real data rather than against a fixture, and")
    lines.append("// the window lets the Rust scanner be re-run over the original bytes.")
    lines.append("//")
    lines.append("// (table, byte offset, window bytes as hex, expression)")
    lines.append("pub const NX1_EXPRESSIONS: &[(&str, usize, &str, &str)] = &[")
    for table, at, window, text in rows:
        lines.append("    // %s at %#x, %d chars" % (table, at, len(text)))
        lines.append("    (%s, %#x, %s, %s),"
                     % (chr(34) + table + chr(34), at,
                        chr(34) + window.hex() + chr(34), put(text)))
    lines.append("];")
    with open(out, "w", encoding="utf-8", newline=chr(10)) as fh:
        fh.write(chr(10).join(lines) + chr(10))

    print("wrote %s" % out)
    print("  %d expressions, %d distinct" % (len(rows), len(set(r[3] for r in rows))))
    tables = {}
    for table, _, _, _ in rows:
        tables[table] = tables.get(table, 0) + 1
    for name, n in sorted(tables.items()):
        print("  %-20s %d" % (name, n))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
