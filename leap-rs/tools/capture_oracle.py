#!/usr/bin/env python3
"""Capture ground truth for the ported calendar functions from the original binary.

Emulates the original functions through GhidraMCP and writes the results as Rust source
(src/oracle_calendar.rs) so the crate can assert parity without any runtime dependency
on Ghidra, Python or the binary itself.

Functions captured:
  0x0042669c  IsLeapYear   -- argument in EAX, 1-byte Boolean in AL
  0x004266d8  day-number encoder -- EAX/EDX/ECX = year/month/day, out-parameter is a
                                     double passed on the stack, returns a Boolean in AL
"""

import argparse
import base64
import json
import random
import struct
import sys
import urllib.request

IS_LEAP = "0042669c"
DAY_NUM = "004266d8"
STACK = 0x20000000
BUF = 0x20000010


def emulate(url, func, regs, memory=None, read_after=None):
    body = {
        "function": func,
        "registers": {k: hex(v) for k, v in regs.items()},
        "memory": memory or [],
        "return_registers": "EAX",
        "max_steps": 20000,
    }
    if read_after:
        body["read_memory_after"] = read_after
    req = urllib.request.Request(url.rstrip("/") + "/emulate_function",
                                 data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"},
                                 method="POST")
    with urllib.request.urlopen(req, timeout=300) as resp:
        return json.loads(resp.read().decode("utf-8", "replace"))


def leap_vector(url, year):
    # Pass the full value in EAX: the original truncates to 16 bits itself
    # (MOVZX CX), so pre-truncating here would hide that behaviour.
    res = emulate(url, IS_LEAP, {"EAX": year & 0xFFFFFFFF})
    if res.get("error") or not res.get("success"):
        raise RuntimeError("emulation failed for year %d: %s" % (year, res))
    return (int(res["registers"]["EAX"], 16) & 0xFF) == 1


def day_vector(url, year, month, day):
    stack = struct.pack("<II", 0xDEADBEEF, BUF)
    res = emulate(url, DAY_NUM,
                  {"EAX": year, "EDX": month, "ECX": day, "ESP": STACK},
                  memory=[{"address": hex(STACK), "data": base64.b64encode(stack).decode()},
                          {"address": hex(BUF), "data": base64.b64encode(b"\x00" * 8).decode()}],
                  read_after=[{"address": hex(BUF), "length": 8}])
    if res.get("error") or not res.get("success"):
        raise RuntimeError("emulation failed for %d-%d-%d: %s" % (year, month, day, res))
    valid = (int(res["registers"]["EAX"], 16) & 0xFF) == 1
    raw = bytes.fromhex(res["memory"][0]["hex"])
    return valid, struct.unpack("<d", raw)[0]


def leap_years():
    ys = list(range(0, 41))
    ys += [96, 100, 104, 200, 300, 400, 1000, 1500, 1582, 1600, 1700, 1800, 1900, 2000,
           2023, 2024, 2100, 2200, 2300, 2400, 2800, 32004, 32768, 40000, 65532, 65535,
           65536, 65537, 131072]
    rng = random.Random(20261012)
    ys += [rng.randrange(0, 65536) for _ in range(240)]
    return sorted(set(ys))


def day_vectors():
    vs = set()
    for y in (1899, 1900, 1996, 2000, 2023, 2024, 2100, 2400):
        for m in range(1, 13):
            vs.add((y, m, 1))
            vs.add((y, m, 28))
            vs.add((y, m, 29))
            vs.add((y, m, 30))
            vs.add((y, m, 31))
    vs |= {(1, 1, 1), (9999, 12, 31), (10000, 1, 1), (0, 6, 15), (2024, 0, 15),
           (2024, 13, 15), (2024, 6, 0)}
    rng = random.Random(20261012)
    while len(vs) < 420:
        vs.add((rng.randrange(0, 10001), rng.randrange(0, 14), rng.randrange(0, 33)))
    return sorted(vs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mcp-url", default="http://127.0.0.1:8089")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    ys = leap_years()
    ds = day_vectors()
    print("capturing %d IsLeapYear vectors and %d date vectors" % (len(ys), len(ds)))

    leap_bits = []
    for y in ys:
        leap_bits.append((y, leap_vector(args.mcp_url, y)))
    print("  IsLeapYear done")

    day_rows = []
    for (y, m, d) in ds:
        valid, value = day_vector(args.mcp_url, y, m, d)
        bits = struct.unpack("<Q", struct.pack("<d", value))[0]
        day_rows.append((y, m, d, valid, bits))
    print("  date encoder done")

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("// GENERATED by tools/capture_oracle.py -- do not edit by hand.\n")
        fh.write("// Ground truth captured from the original binary by emulation.\n\n")
        fh.write("/// (year, expected Boolean) for the original at 0x0042669c.\n")
        fh.write("pub const IS_LEAP_YEAR_VECTORS: &[(u32, bool)] = &[\n")
        for y, b in leap_bits:
            fh.write("    (%d, %s),\n" % (y, "true" if b else "false"))
        fh.write("];\n\n")
        fh.write("/// (year, month, day, valid, out-parameter bits) for the original at 0x004266d8.\n")
        fh.write("pub const DAY_NUMBER_VECTORS: &[(u16, u16, u16, bool, u64)] = &[\n")
        for y, m, d, valid, bits in day_rows:
            fh.write("    (%d, %d, %d, %s, 0x%016x),\n" % (y, m, d, "true" if valid else "false", bits))
        fh.write("];\n")

    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
