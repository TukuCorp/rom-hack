#!/usr/bin/env python3
"""Capture ground truth for the TestLEAP command line as a whole, not one archive.

The chain in container.rs decides a single archive. entry wraps it in a loop over the
arguments, and this oracle pins that loop: the exit code is the LAST argument verdict,
the messages are printed in argument order, and an argument that resolves to no file at
all gives verdict -1 with its own message.

Wildcard expansion itself is deliberately not captured. FindFirstFile order is not a
property of the program, so only the case where a wildcard matches nothing is used, and
every other vector names its files explicitly.

Writes src/oracle_run.rs.
"""

import argparse
import os
import subprocess
import sys
import tempfile
import zipfile

TESTLEAP = "C:/Program Files/LEAP/testleap.exe"
REQ = ["masterstructure.nx1", "areadata.nx1", "scenariodata.nx1", "staticdata.nx1",
       "scenariodata.nx1", "years.nx1"]

MODES = (("default", []), ("/S", ["/S"]), ("/Q", ["/Q"]), ("/N", ["/N"]))


def archives():
    """Name -> members, or raw bytes when the member list is None."""
    return [
        ("good", REQ, None),
        ("db", REQ + ["masterstructure.db"], None),
        ("bad", None, b"not a zip at all"),
    ]


def build(tmpdir, name, members, payload):
    path = os.path.join(tmpdir, name + ".leap")
    if payload is not None:
        with open(path, "wb") as fh:
            fh.write(payload)
        return
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        for m in members:
            zf.writestr(m, "x")
        zf.writestr("sysinfo.txt", "Area Name: VN" + chr(10))


def vectors():
    return [
        ("single_good", ["good"]),
        ("single_bad", ["bad"]),
        ("single_db", ["db"]),
        ("good_then_bad", ["good", "bad"]),
        ("bad_then_good", ["bad", "good"]),
        ("good_then_db", ["good", "db"]),
        ("db_then_bad", ["db", "bad"]),
        ("three_files", ["good", "bad", "db"]),
        ("repeat_same_file", ["good", "good"]),
        ("missing_only", ["nosuch.leap"]),
        ("missing_then_good", ["nosuch.leap", "good"]),
        ("good_then_missing", ["good", "nosuch.leap"]),
        ("wildcard_matches_nothing", ["*.nothing"]),
        ("missing_then_missing", ["a.nope", "b.nope"]),
    ]


def run(cwd, args):
    p = subprocess.run([TESTLEAP] + args, cwd=cwd, capture_output=True, timeout=120)
    code = p.returncode
    if code > 2 ** 31:
        code -= 2 ** 32
    return code, (p.stdout or b"").decode("latin-1")


def esc(s):
    bs = chr(92)
    out = []
    for ch in s:
        if ch == bs:
            out.append(bs + bs)
        elif ch == chr(34):
            out.append(bs + chr(34))
        elif ch == chr(10):
            out.append(bs + "n")
        elif ch == chr(13):
            out.append(bs + "r")
        else:
            out.append(ch)
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    if not os.path.exists(TESTLEAP):
        print("missing %s" % TESTLEAP, file=sys.stderr)
        return 1

    q = chr(34)
    tmpdir = tempfile.mkdtemp(prefix="leap_runvec_")
    for name, members, payload in archives():
        build(tmpdir, name, members, payload)

    rows = []
    for case, files in vectors():
        outs = []
        codes = set()
        for _label, flags in MODES:
            # A bare name means the archive; anything else is passed through untouched.
            argv = []
            for f in files:
                argv.append(f + ".leap" if f in [a[0] for a in archives()] else f)
            code, out = run(tmpdir, argv + flags)
            codes.add(code)
            outs.append(out)
        if len(codes) != 1:
            print("verdict differs between modes for %s: %s" % (case, sorted(codes)),
                  file=sys.stderr)
            return 1
        rows.append((case, files, codes.pop(), outs))

    usage_code, usage_text = run(tmpdir, [])

    lines = []
    lines.append("// GENERATED by tools/capture_run_oracle.py -- do not edit by hand.")
    lines.append("// Ground truth for the TestLEAP argument loop, captured four ways.")
    lines.append("//")
    lines.append("// (case, arguments as typed, exit code, default stdout, /S, /Q, /N)")
    lines.append("pub const RUN_VECTORS: &[(&str, &[&str], i32, &str, &str, &str, &str)] = &[")
    for case, files, code, outs in rows:
        listed = ", ".join(q + f + ".leap" + q if f in [a[0] for a in archives()] else q + f + q
                           for f in files)
        cells = [q + case + q, "&[" + listed + "]", str(code)]
        cells += [q + esc(o) + q for o in outs]
        lines.append("    (" + ", ".join(cells) + "),")
    lines.append("];")
    lines.append("")
    lines.append("/// The archives the vectors refer to, so the test can supply the same bytes.")
    lines.append("pub const RUN_ARCHIVES: &[(&str, &str)] = &[")
    for name, members, payload in archives():
        if payload is not None:
            blob = payload
        else:
            blob = None
        if blob is None:
            with open(os.path.join(tmpdir, name + ".leap"), "rb") as fh:
                blob = fh.read()
        lines.append('    ("%s", "%s"),' % (name, blob.hex()))
    lines.append("];")
    lines.append("")
    lines.append("/// What the program prints when handed no arguments at all, and its exit code.")
    lines.append('pub const RUN_USAGE: &str = "%s";' % esc(usage_text))
    lines.append("pub const RUN_USAGE_CODE: i32 = %d;" % usage_code)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(chr(10).join(lines) + chr(10))

    print("wrote %s with %d run vectors" % (args.out, len(rows)))
    for case, files, code, outs in rows:
        print("  %-26s exit=%-4s default=%r" % (case, code, outs[0]))
    print("  usage exit=%s text=%r" % (usage_code, usage_text))
    return 0


if __name__ == "__main__":
    sys.exit(main())